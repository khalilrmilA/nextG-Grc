def _introspect_schema():
    """Walk Base.metadata.tables (populated by `import app.models`) into a plain
    {table_name: [(col_name, type_str, nullable, fk_target_or_None), ...]} dict,
    alphabetically ordered by table name."""
    schema = {}
    for name in sorted(Base.metadata.tables.keys()):
        table = Base.metadata.tables[name]
        cols = []
        for c in table.columns:
            fk = next(iter(c.foreign_keys), None)
            cols.append((c.name, str(c.type), bool(c.nullable), fk.target_fullname if fk else None))
        schema[name] = cols
    return schema


