# ── Reusable flowable builders ───────────────────────────────────────────────

def _table_block(headers, rows, widths_frac, page_w, ss):
    hdr = [Paragraph(f"<b>{h}</b>", ss["TblCellB"]) for h in headers]
    body = [[Paragraph(str(c), ss["TblCell"]) for c in row] for row in rows]
    data = [hdr] + body
    widths = [page_w * f for f in widths_frac] if widths_frac else [page_w / len(headers)] * len(headers)
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), NAVY),
        ("TOPPADDING", (0, 0), (-1, 0), 5), ("BOTTOMPADDING", (0, 0), (-1, 0), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 6), ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 1), (-1, -1), 4), ("BOTTOMPADDING", (0, 1), (-1, -1), 4),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [WHITE, GRAY_100]),
        ("LINEBELOW", (0, 0), (-1, -1), 0.3, GRAY_300),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    return t


def _note_box(text, page_w, ss):
    p = Paragraph(text, ss["Note"])
    t = Table([[p]], colWidths=[page_w])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), GRAY_100),
        ("LINEBEFORE", (0, 0), (0, -1), 3, ORANGE),
        ("TOPPADDING", (0, 0), (-1, -1), 8), ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("LEFTPADDING", (0, 0), (-1, -1), 10), ("RIGHTPADDING", (0, 0), (-1, -1), 10),
    ]))
    return t


def _dict_table_flowable(ss, table_name, cols, page_w, lang):
    n_label = "colonnes" if lang == "fr" else "columns"
    bar = Paragraph(f"<b>{table_name}</b>  ({len(cols)} {n_label})", ss["DictBar"])
    col_hdr = ["Colonne", "Type", "Null", "Clé étrangère"] if lang == "fr" else ["Column", "Type", "Nullable", "Foreign key"]
    hdr_row = [Paragraph(h, ss["DictHead"]) for h in col_hdr]
    data = [[bar, "", "", ""], hdr_row]
    yes, no = ("Oui", "Non") if lang == "fr" else ("Yes", "No")
    for name, typ, nullable, fk in cols:
        data.append([
            Paragraph(name, ss["DictCell"]),
            Paragraph(typ, ss["DictCell"]),
            Paragraph(yes if nullable else no, ss["DictCell"]),
            Paragraph(("→ " + fk) if fk else "—", ss["DictCell"]),
        ])
    widths = [page_w * 0.27, page_w * 0.30, page_w * 0.11, page_w * 0.32]
    t = Table(data, colWidths=widths, repeatRows=2)
    t.setStyle(TableStyle([
        ("SPAN", (0, 0), (-1, 0)),
        ("BACKGROUND", (0, 0), (-1, 0), DARK_BLUE),
        ("TOPPADDING", (0, 0), (-1, 0), 3), ("BOTTOMPADDING", (0, 0), (-1, 0), 3), ("LEFTPADDING", (0, 0), (-1, 0), 6),
        ("BACKGROUND", (0, 1), (-1, 1), GRAY_100),
        ("TOPPADDING", (0, 1), (-1, -1), 2), ("BOTTOMPADDING", (0, 1), (-1, -1), 2), ("LEFTPADDING", (0, 1), (-1, -1), 4),
        ("ROWBACKGROUNDS", (0, 2), (-1, -1), [WHITE, colors.HexColor("#fafafa")]),
        ("LINEBELOW", (0, 0), (-1, -1), 0.3, GRAY_300),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    return t


def _render(blocks, ss, page_w):
    els = []
    for b in blocks:
        kind = b[0]
        if kind == "h1":
            els.append(Paragraph(b[1], ss["H1"]))
        elif kind == "h2":
            els.append(Paragraph(b[1], ss["H2"]))
        elif kind == "h3":
            els.append(Paragraph(b[1], ss["H3"]))
        elif kind == "p":
            els.append(Paragraph(b[1], ss["Body"]))
        elif kind == "bul":
            for item in b[1]:
                els.append(Paragraph(f"•  {item}", ss["Bul"]))
            els.append(Spacer(1, 3))
        elif kind == "tbl":
            headers, rows = b[1], b[2]
            widths = b[3] if len(b) > 3 else None
            els.append(_table_block(headers, rows, widths, page_w, ss))
            els.append(Spacer(1, 10))
        elif kind == "note":
            els.append(_note_box(b[1], page_w, ss))
            els.append(Spacer(1, 8))
        elif kind == "dicttable":
            _name, cols, lang = b[1], b[2], b[3]
            els.append(_dict_table_flowable(ss, _name, cols, page_w, lang))
            els.append(Spacer(1, 8))
        elif kind == "space":
            els.append(Spacer(1, b[1]))
        elif kind == "break":
            els.append(PageBreak())
        elif kind == "hr":
            els.append(HRFlowable(width="100%", thickness=0.5, color=GRAY_300, spaceBefore=6, spaceAfter=6))
        elif kind == "raw":
            els.append(b[1])
    return els


def _footer_cb(doc_code, footer_note):
    def _cb(canvas, doc):
        canvas.saveState()
        canvas.setStrokeColor(GRAY_300)
        canvas.setLineWidth(0.5)
        canvas.line(doc.leftMargin, 0.5 * inch, doc.pagesize[0] - doc.rightMargin, 0.5 * inch)
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(GRAY_500)
        canvas.drawString(doc.leftMargin, 0.34 * inch, footer_note)
        canvas.drawRightString(doc.pagesize[0] - doc.rightMargin, 0.34 * inch, f"{doc_code} — Page {canvas.getPageNumber()}")
        canvas.restoreState()
    return _cb


def build_pdf(filename, title, subtitle, meta_line, blocks, landscape_mode=False, doc_code="", footer_note=""):
    path = os.path.join(OUT_DIR, filename)
    pagesize = landscape(A4) if landscape_mode else A4
    doc = SimpleDocTemplate(
        path, pagesize=pagesize,
        leftMargin=0.7 * inch, rightMargin=0.7 * inch,
        topMargin=0.6 * inch, bottomMargin=0.65 * inch,
    )
    ss = _styles()
    page_w = pagesize[0] - doc.leftMargin - doc.rightMargin
    els = [
        HRFlowable(width="100%", thickness=2, color=NAVY, spaceAfter=6),
        Paragraph(title, ss["DocTitle"]),
        Paragraph(subtitle, ss["DocSubtitle"]),
    ]
    if meta_line:
        els.append(Paragraph(meta_line, ss["Small"]))
    els.append(HRFlowable(width="100%", thickness=0.5, color=GRAY_300, spaceBefore=6, spaceAfter=12))
    els.extend(_render(blocks, ss, page_w))
    doc.build(els, onFirstPage=_footer_cb(doc_code, footer_note), onLaterPages=_footer_cb(doc_code, footer_note))
    print(f"  -> {path}  ({os.path.getsize(path) // 1024} KB)")
    return path


