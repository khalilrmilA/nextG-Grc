#!/usr/bin/env bash
# Compile the application and destroy every trace of its source.
#
#   PROTECT_LEVEL=bundle     run from the virtualenv, source intact. Fast builds.
#   PROTECT_LEVEL=obfuscate  byte-compile, delete every .py. Decompilable.
#   PROTECT_LEVEL=binary     Nuitka standalone compile to C. Default for release.
#
# Runs after 20-app.sh and before 30-harden.sh.
#
# A note on what "binary" does and does not remove. The API is Python, so the
# Node SEA approach the original scaffold described does not apply. Nuitka is
# the equivalent: it compiles the application to C extension modules plus a
# launcher, and the shipped dist carries its own libpython, so no application
# source and no application bytecode remain on the image.
#
# The SYSTEM python3 stays. Ubuntu's netplan command line tool is Python, and
# firstboot.sh calls "netplan apply" through netconfig.sh, so purging the
# interpreter would leave the appliance unable to configure its own network.
# What is removed is the application: its source, its bytecode and its
# virtualenv. Be precise about this in customer-facing claims.
set -euo pipefail

APP_DIR=/opt/appliance
BACKEND_DIR="${APP_DIR}/backend"
VENV="${BACKEND_DIR}/venv"
INSTALL_DIR="${APP_DIR}/runtime"
LEVEL="${PROTECT_LEVEL:-binary}"
BUILD_TMP=/tmp/protect-build

echo "[25-protect] level: ${LEVEL}"

case "${LEVEL}" in
  bundle|obfuscate|binary) ;;
  *) echo "[25-protect] FATAL: unknown PROTECT_LEVEL '${LEVEL}'" >&2; exit 1 ;;
esac

install -d -m 0755 "${INSTALL_DIR}"
rm -rf "${BUILD_TMP}"
install -d -m 0755 "${BUILD_TMP}"

# ---------------------------------------------------------------------------
# Bake the licence constants in BEFORE compiling.
#
# app/core/build_info.py documents exactly this: the protected client build
# overwrites the file so a customer cannot turn enforcement off or swap the
# public key through an environment variable. Only the PUBLIC key is ever
# written; the private key stays on the vendor's infrastructure.
# ---------------------------------------------------------------------------
if [ -n "${LICENSE_PUBLIC_KEY:-}" ]; then
  echo "[25-protect] baking licence enforcement into build_info.py"
  cat > "${BACKEND_DIR}/app/core/build_info.py" <<EOF
"""Build-time license constants. Generated by 25-protect-app.sh; do not edit."""

LICENSED_BUILD = ${LICENSE_ENFORCEMENT_BUILD:-True}
LICENSE_PUBLIC_KEY = "${LICENSE_PUBLIC_KEY}"
EOF
else
  echo "[25-protect] WARN: LICENSE_PUBLIC_KEY not set; shipping with enforcement off"
fi

# ---------------------------------------------------------------------------
if [ "${LEVEL}" = "binary" ]; then
  echo "[25-protect] compiling with Nuitka (this is the slow step)"
  "${VENV}/bin/pip" install --no-cache-dir "nuitka==2.5.*" ordered-set zstandard >/dev/null

  # ---------------------------------------------------------------------------
  # Drop dependencies that are installed but never imported.
  #
  # requirements.txt pulls in pgvector, which drags in numpy. Nothing in the
  # application imports either one. That would just be wasted image size, except
  # that numpy uses PEP 695 generic type aliases ("type NDArray[ScalarT] = ...")
  # and Nuitka 2.5 cannot parse them: it dies with
  #
  #   ReformulationAssignmentStatements.py, in buildTypeAliasNode
  #   assert not node.type_params
  #   AssertionError: [<ast.TypeVar object ...>]
  #
  # Removing them before compiling is better than excluding them at the Nuitka
  # level, because it also keeps them out of the shipped image.
  echo "[25-protect] removing dependencies nothing imports (pgvector, numpy)"
  "${VENV}/bin/pip" uninstall -y pgvector numpy >/dev/null 2>&1 || true

  # ---------------------------------------------------------------------------
  # Cap the parallel C compilation by MEMORY, not by core count.
  #
  # Nuitka defaults --jobs to the number of CPUs. Compiling Nuitka-generated C
  # costs roughly 1.5 GB per concurrent cc1, so on a 6 vCPU / 6 GB guest the
  # default spawns six compilers against four jobs' worth of RAM. The guest then
  # thrashes and the kernel logs:
  #
  #   watchdog: BUG: soft lockup - CPU#1 stuck for 22s! [cc1:9216]
  #   watchdog: BUG: soft lockup - CPU#3 stuck for 22s! [kswapd0:83]
  #
  # kswapd0 in that list is the giveaway: it is memory reclaim, not CPU
  # starvation. Worst case the OOM killer takes a cc1 and the build fails after
  # an hour. Deriving jobs from available memory keeps adding vCPUs safe.
  # 1536 MB per concurrent cc1, and 1536 MB reserved for the guest OS, page
  # cache and the Python half of Nuitka that stays resident. Without that
  # reserve the formula hands every last megabyte to the compilers and the
  # kernel starts reclaiming, which is the failure this whole block exists to
  # prevent.
  MEM_MB="$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)"
  CPU_N="$(nproc)"
  MEM_JOBS=$(( (MEM_MB - 1536) / 1536 ))
  [ "${MEM_JOBS}" -lt 1 ] && MEM_JOBS=1
  NUITKA_JOBS="${NUITKA_JOBS:-$(( MEM_JOBS < CPU_N ? MEM_JOBS : CPU_N ))}"
  echo "[25-protect] ${CPU_N} cpus, ${MEM_MB} MB RAM -> --jobs=${NUITKA_JOBS}"

  cd "${BACKEND_DIR}"
  # NUITKA_EXTRA_ARGS is deliberately unquoted below: it carries several
  # separate arguments and must word-split. Set it to add one-off excludes
  # without editing this script, e.g.
  #   NUITKA_EXTRA_ARGS="--nofollow-import-to=pandas"
  # --include-package-data is separate from --include-package and is the one
  # that is easy to forget: Nuitka bundles a package's .py modules but NOT the
  # data files beside them. Every miss is a FileNotFoundError at run time, an
  # hour into a build. Two have already cost a build each:
  #   certifi -> cacert.pem
  #   limits  -> resources/redis/lua_scripts/moving_window.lua
  # The list below came from installing requirements.txt and enumerating every
  # dependency shipping non-Python files, not from hitting them one at a time.
  # docx is there because python-docx renders from XML templates, and document
  # generation would otherwise fail only once a customer used it.
  #
  # The celery stack (celery, kombu, billiard, amqp, vine) is listed for the
  # OTHER reason: celery resolves its loader class from a STRING at run time,
  # through kombu.utils.imports.symbol_by_name into importlib.import_module.
  # Static analysis cannot see that by definition, so Nuitka never bundled it and
  # the compiled binary died the moment anything touched the task registry:
  #     ModuleNotFoundError: No module named 'celery.loaders.default'
  # app/api/v1/endpoints/ai_access.py triggers exactly that at import, so it hit
  # every boot. Naming the whole stack pulls in the submodules the string lookups
  # reach for.
  # certifi and sentry_sdk are listed because app/main.py imports sentry_sdk
  # unconditionally and that reaches certifi. Bundling them is necessary but is
  # NOT sufficient on its own: see the branch-collapsing step above, which is
  # what actually makes certifi importable once compiled.
  # --include-package is needed wherever a dependency resolves a submodule by
  # string at runtime: uvicorn picks its protocol implementation that way,
  # SQLAlchemy loads dialects that way, passlib loads password handlers that
  # way. Nuitka cannot see those from static analysis, and a missing one fails
  # at run time rather than at compile time, which is why the smoke test below
  # is not optional.
  # -------------------------------------------------------------------------
  # Collapse certifi to its modern branch BEFORE compiling.
  #
  # certifi/core.py chooses between two implementations with
  #     if sys.version_info >= (3, 11): ...  else: ...
  # Nuitka resolves that test the wrong way round and keeps the LEGACY branch,
  # whose 'from importlib.resources import path as get_path, read_text' then
  # fails at import with a bare, message-less ImportError:
  #
  #     File ".../certifi/core.py", line 51, in <module certifi.core>
  #     ImportError
  #
  # Proven, not guessed: deleting the else branch changed the error to
  # "cannot import name 'contents'", and contents is defined in the IF branch,
  # so the IF branch was the half being discarded. Reproduced standalone and
  # confirmed fixed by this rewrite before it was put here.
  #
  # This is not cosmetic. app/main.py imports sentry_sdk, which imports certifi,
  # so 'serve' died on every boot and the web console never answered. httpx
  # resolves its trust store the same way, so licence activation over TLS was
  # broken too. The appliance is always Python 3.11+, so the legacy branch is
  # dead code; removing the choice removes the bug.
  CERTIFI_CORE="$("${VENV}/bin/python" -c 'import certifi.core as c; print(c.__file__)')"
  if [ -z "${CERTIFI_CORE}" ] || [ ! -f "${CERTIFI_CORE}" ]; then
    echo "[25-protect] FATAL: could not locate certifi/core.py" >&2
    exit 1
  fi
  cat > "${CERTIFI_CORE}" <<'CERTIFI_EOF'
"""certifi.core, rewritten at appliance build time.

Upstream guards two implementations behind a sys.version_info test that Nuitka
resolves the wrong way round. See scripts/25-protect-app.sh for the full
explanation. Only the Python 3.11+ implementation is kept here.
"""
import atexit

from importlib.resources import as_file, files

_CACERT_CTX = None
_CACERT_PATH = None


def exit_cacert_ctx() -> None:
    _CACERT_CTX.__exit__(None, None, None)


def where() -> str:
    global _CACERT_CTX, _CACERT_PATH
    if _CACERT_PATH is None:
        _CACERT_CTX = as_file(files("certifi").joinpath("cacert.pem"))
        _CACERT_PATH = str(_CACERT_CTX.__enter__())
        atexit.register(exit_cacert_ctx)
    return _CACERT_PATH


def contents() -> str:
    return files("certifi").joinpath("cacert.pem").read_text(encoding="ascii")
CERTIFI_EOF

  # Prove the rewrite imports before spending 35 minutes compiling it.
  if ! "${VENV}/bin/python" -c 'import certifi; assert certifi.where().endswith("cacert.pem")'; then
    echo "[25-protect] FATAL: the rewritten certifi does not import" >&2
    exit 1
  fi
  echo "[25-protect] certifi collapsed to its modern branch"
  # shellcheck disable=SC2086
  "${VENV}/bin/python" -m nuitka \
    --standalone \
    --jobs="${NUITKA_JOBS}" \
    --assume-yes-for-downloads \
    --output-dir="${BUILD_TMP}" \
    --output-filename=appliance-api \
    --company-name="${APPLIANCE_VENDOR:-Appliance}" \
    --product-name="${APPLIANCE_NAME:-appliance}" \
    --product-version="${APPLIANCE_VERSION:-1.0.0}" \
    --include-package=app \
    --include-package=scripts \
    --include-package=uvicorn \
    --include-package=fastapi \
    --include-package=starlette \
    --include-package=pydantic \
    --include-package=pydantic_settings \
    --include-package=sqlalchemy \
    --include-package=aiosqlite \
    --include-package=passlib \
    --include-package=jose \
    --include-package=argon2 \
    --include-package=bcrypt \
    --include-package=jinja2 \
    --include-package=httpx \
    --include-package=cryptography \
    --include-package=email_validator \
    --include-package=structlog \
    --include-package=slowapi \
    --include-package=pyotp \
    --include-package=yaml \
    --include-package=reportlab \
    --include-package-data=reportlab \
    --include-package=sentry_sdk \
    --include-package=certifi \
    --include-package-data=certifi \
    --include-package=limits \
    --include-package-data=limits \
    --include-package=docx \
    --include-package-data=docx \
    --include-package=celery \
    --include-package=kombu \
    --include-package=billiard \
    --include-package=amqp \
    --include-package=vine \
    --include-package-data=dateutil \
    --include-package-data=tzdata \
    --include-data-dir=app/templates=app/templates \
    --nofollow-import-to=numpy \
    --nofollow-import-to=pgvector \
    --nofollow-import-to=pytest \
    --nofollow-import-to=setuptools \
    ${NUITKA_EXTRA_ARGS:-} \
    --remove-output \
    appliance_cli.py

  # Nuitka writes <name>.dist/ holding the launcher and every shared object.
  rm -rf "${INSTALL_DIR:?}/"*
  cp -a "${BUILD_TMP}/appliance_cli.dist/." "${INSTALL_DIR}/"
  EXEC_PATH="${INSTALL_DIR}/appliance-api"
  [ -x "${EXEC_PATH}" ] || { echo "[25-protect] FATAL: Nuitka produced no binary" >&2; exit 1; }

elif [ "${LEVEL}" = "obfuscate" ]; then
  echo "[25-protect] byte-compiling and removing source"
  "${VENV}/bin/python" -m compileall -b -q "${BACKEND_DIR}/app" "${BACKEND_DIR}/scripts" \
    "${BACKEND_DIR}/appliance_cli.py"
  find "${BACKEND_DIR}" -name '*.py' -delete
  find "${BACKEND_DIR}" -name '__pycache__' -type d -prune -exec rm -rf {} + 2>/dev/null || true
  cat > "${INSTALL_DIR}/appliance-api" <<EOF
#!/bin/sh
exec "${VENV}/bin/python" "${BACKEND_DIR}/appliance_cli.pyc" "\$@"
EOF
  chmod 0755 "${INSTALL_DIR}/appliance-api"
  EXEC_PATH="${INSTALL_DIR}/appliance-api"

else
  echo "[25-protect] bundle level: running from the virtualenv, source retained"
  cat > "${INSTALL_DIR}/appliance-api" <<EOF
#!/bin/sh
exec "${VENV}/bin/python" "${BACKEND_DIR}/appliance_cli.py" "\$@"
EOF
  chmod 0755 "${INSTALL_DIR}/appliance-api"
  EXEC_PATH="${INSTALL_DIR}/appliance-api"
fi

# ---------------------------------------------------------------------------
# Smoke test the artefact before anything is deleted.
#
# A Nuitka build that is missing a lazily imported module compiles cleanly and
# then fails on the customer's first boot. Exercising the two subcommands
# firstboot depends on, here, turns that into a build failure instead.
# ---------------------------------------------------------------------------
echo "[25-protect] smoke testing the built artefact"
# Run as the SERVICE user, not as root.
#
# Root can read files the appliance user cannot, so a root-only smoke test
# happily passes on a permission layout the real service will fail on. That is
# not hypothetical: mode 0040/0050 (owner with no permissions) passed here and
# then broke first boot once AppArmor removed root's CAP_DAC_OVERRIDE.
SMOKE_DIR=/tmp/protect-smoke
SMOKE_DB="${SMOKE_DIR}/smoke.db"
SMOKE_URL="sqlite+aiosqlite:///${SMOKE_DB}"
rm -rf "${SMOKE_DIR}"
install -d -m 0770 -o appliance -g appliance "${SMOKE_DIR}"

as_service() {
  runuser -u appliance -- env ENVIRONMENT=development DATABASE_URL="${SMOKE_URL}" "$@"
}

as_service "${EXEC_PATH}" version \
  || { echo "[25-protect] FATAL: 'version' failed as the service user" >&2; exit 1; }

as_service "${EXEC_PATH}" migrate \
  || { echo "[25-protect] FATAL: 'migrate' failed as the service user" >&2; exit 1; }

as_service "${EXEC_PATH}" create-admin --email smoke@localhost --generate \
    --password-out "${SMOKE_DIR}/smoke.pass" \
  || { echo "[25-protect] FATAL: 'create-admin' failed as the service user" >&2; exit 1; }

[ -s "${SMOKE_DIR}/smoke.pass" ] \
  || { echo "[25-protect] FATAL: create-admin produced no password" >&2; exit 1; }

rm -rf "${SMOKE_DIR}"
echo "[25-protect] smoke test passed"

# ---------------------------------------------------------------------------
echo "[25-protect] pointing the service at ${EXEC_PATH}"
sed -i "s|^ExecStart=.*|ExecStart=${EXEC_PATH} serve|" /etc/systemd/system/appliance-api.service
systemctl daemon-reload

# ---------------------------------------------------------------------------
echo "[25-protect] removing the source tree"
if [ "${LEVEL}" = "binary" ]; then
  # Nothing under backend/ is needed once the binary is standalone.
  rm -rf "${BACKEND_DIR}"
else
  # bundle and obfuscate still execute out of the virtualenv, so only the
  # build inputs go.
  rm -rf "${BACKEND_DIR}/.git"
fi
rm -rf "${BUILD_TMP}" /tmp/app /tmp/frontend-build /root/.npm /root/.cache/pip
find "${APP_DIR}" -name '*.map' -delete 2>/dev/null || true
find "${APP_DIR}" -name '.git' -prune -exec rm -rf {} + 2>/dev/null || true

# ---------------------------------------------------------------------------
echo "[25-protect] restricting the runtime directory"
# The LAUNCHER is execute-only for the service: mode 0710 means the appliance
# group may execute it but not read it, so a remote code execution flaw in the
# web application cannot copy the product out.
#
# The shared objects CANNOT be execute-only. A Nuitka standalone build is a
# launcher plus a few hundred .so files that it dlopen()s, and dlopen needs
# read permission. They are therefore 0640 root:appliance: readable by the
# service, unreadable by anyone else. Be precise about this in customer-facing
# claims: the launcher is unreadable, the shared objects are not.
#
# What must NOT be done, and was: mode 0040/0050 leaves the OWNER with no
# permissions at all. Root normally bypasses that with CAP_DAC_OVERRIDE, which
# is why the smoke test above passed. But 35-lockdown.sh then loads an AppArmor
# profile, AppArmor denies every capability it does not grant, and at first boot
# the confined process loses dac_override. The result is:
#
#   ImportError: /opt/appliance/runtime/_contextvars.so:
#                cannot open shared object file: Permission denied
#   [firstboot] FATAL: database migration failed
#
# The image builds, the smoke test passes, and the appliance is dead on the
# customer's first boot. Give the owner real permissions.
chown -R root:appliance "${INSTALL_DIR}"
find "${INSTALL_DIR}" -type d -exec chmod 0750 {} +
find "${INSTALL_DIR}" -type f -exec chmod 0640 {} +
chmod 0710 "${EXEC_PATH}"

if [ "${LEVEL}" = "binary" ]; then
  echo "[25-protect] removing the Node.js build toolchain"
  # Node existed only to build the React bundle, which is now static files.
  apt-get -y purge nodejs >/dev/null 2>&1 || true
  rm -f /etc/apt/sources.list.d/nodesource.list /etc/apt/keyrings/nodesource.gpg
fi

echo "[25-protect] done (${LEVEL})"
