"""Online licence activation client.

The appliance normally has no reason to talk to anything. This module is the
single exception, and it is deliberately narrow:

  - It runs only when an administrator explicitly activates a licence from the
    web console. Nothing here is on a timer, nothing runs at boot, and nothing
    runs unless LICENSE_SERVER_URL is configured. An air-gapped appliance never
    reaches this code, and offline activation (paste a signed key) stays fully
    supported through POST /license/activate.
  - It sends the minimum needed to identify the entitlement being claimed: the
    activation code the customer was given, the machine id, and the product and
    version. No customer data, no inventory, no usage counters, no telemetry.
  - It changes no trust decision. The server hands back an Ed25519 signed
    licence key which is then verified locally against the public key baked into
    the build, exactly as a pasted key would be. A compromised or spoofed
    licence server cannot mint a licence this appliance will accept.

In other words the network is a transport convenience for fetching a key the
appliance would otherwise be given by email. It is not an authority.
"""
from __future__ import annotations

import logging

import httpx

from app.core.config import settings

logger = logging.getLogger(__name__)

ACTIVATION_PATH = "/api/v1/licenses/activate"
TIMEOUT_SECONDS = 15.0
MACHINE_ID_FILE = "/etc/machine-id"


class LicenseServerError(RuntimeError):
    """Raised when the licence server cannot be reached or refuses the code."""


def server_configured() -> bool:
    return bool((settings.LICENSE_SERVER_URL or "").strip())


def read_machine_id() -> str:
    """Stable per-deployment identifier, regenerated by firstboot on each clone."""
    try:
        with open(MACHINE_ID_FILE, encoding="utf-8") as handle:
            return handle.readline().strip()
    except OSError:
        return ""


async def fetch_license_key(activation_code: str) -> str:
    """Exchange an activation code for a signed licence key.

    Returns the licence key string. Raises LicenseServerError with a message
    fit to show an administrator; the caller verifies the key locally before
    trusting any of it.
    """
    base = (settings.LICENSE_SERVER_URL or "").strip().rstrip("/")
    if not base:
        raise LicenseServerError(
            "No licence server is configured. Use offline activation instead: "
            "paste the licence key you were issued."
        )

    payload = {
        "activation_code": activation_code.strip(),
        "machine_id": read_machine_id(),
        "product": "grc-platform",
        "version": settings.APP_VERSION,
    }

    try:
        # follow_redirects stays off: a redirect to another host would leak the
        # activation code somewhere the operator did not configure.
        async with httpx.AsyncClient(timeout=TIMEOUT_SECONDS, follow_redirects=False) as client:
            response = await client.post(base + ACTIVATION_PATH, json=payload)
    except httpx.TimeoutException as exc:
        raise LicenseServerError(
            f"Licence server did not respond within {int(TIMEOUT_SECONDS)}s. "
            "Check outbound connectivity, or activate offline."
        ) from exc
    except httpx.HTTPError as exc:
        raise LicenseServerError(
            f"Could not reach the licence server: {exc}. Activate offline instead."
        ) from exc

    if response.status_code in (401, 403):
        raise LicenseServerError("Activation code was rejected by the licence server.")
    if response.status_code == 404:
        raise LicenseServerError("Activation code not found on the licence server.")
    if response.status_code == 409:
        raise LicenseServerError(
            "This activation code has already been used on another deployment."
        )
    if response.status_code >= 400:
        raise LicenseServerError(
            f"Licence server returned {response.status_code}. Activate offline instead."
        )

    try:
        body = response.json()
    except ValueError as exc:
        raise LicenseServerError("Licence server returned a malformed response.") from exc

    key = (body or {}).get("license_key", "")
    if not isinstance(key, str) or not key.strip():
        raise LicenseServerError("Licence server returned no licence key.")

    logger.info("Fetched a licence key from the licence server")
    return key.strip()
